"""Clean the Data"""

# CELL 4: Clean the data

# 1. Start fresh from the original file, so old runs can't interfere
df = pd.read_csv("SMSSpamCollection", sep="\t", names=["label", "text"])
before = len(df)

# 2. Tidy the labels (remove spaces, make lowercase)
df["label"] = df["label"].str.strip().str.lower()

# 3. Remove missing values and repeated messages
df = df.dropna()
df = df.drop_duplicates()
df = df.reset_index(drop=True)

# 4. Clean the message text
df["clean"] = (
    df["text"]
    .str.lower()                                      # lowercase
    .str.replace(r"http\S+|www\S+", " url ", regex=True)   # links become the word "url"
    .str.replace(r"\d+", " num ", regex=True)         # numbers become the word "num"
    .str.replace(r"[^a-z\s]", " ", regex=True)        # remove symbols
    .str.replace(r"\s+", " ", regex=True)             # remove extra spaces
    .str.strip()
)

# 5. Remove any message that became empty after cleaning
df = df[df["clean"] != ""].reset_index(drop=True)

# 6. Check that everything is fine
print("Rows before:", before, "| after:", len(df))
print("\nLabel counts:")
print(df["label"].value_counts())
print("\nMissing values:")
print(df.isnull().sum())
print("\nExample of cleaning:")
print(df[["text", "clean"]].head())

# 7. Chart: before and after
plt.bar(["Before", "After"], [before, len(df)], color=["gray", "seagreen"])
plt.title("Rows before and after cleaning")
plt.show()

"""Separate data and labels"""

X = df["clean"]                      # the messages (data)
y = (df.label == "spam").astype(int) # the answers: 1 = spam, 0 = ham
print(X.shape, y.shape)
y.value_counts().plot(kind="pie", labels=["Ham","Spam"], autopct="%1.1f%%", colors=["steelblue","tomato"])
plt.title("Labels")
plt.show()

"""Split into learning and testing parts"""

from sklearn.model_selection import train_test_split
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=42)
print("Train:", len(X_train), "| Test:", len(X_test))

"""Convert words to numbers (TF-IDF)"""

from sklearn.feature_extraction.text import TfidfVectorizer
tfidf = TfidfVectorizer(stop_words="english")
X_train_num = tfidf.fit_transform(X_train)
X_test_num = tfidf.transform(X_test)
print("Shape:", X_train_num.shape)

import numpy as np
scores = np.asarray(X_train_num.mean(axis=0)).ravel()
top = scores.argsort()[-15:]
words = tfidf.get_feature_names_out()
plt.barh(words[top], scores[top], color="teal")
plt.title("Top 15 words by TF-IDF weight")
plt.show()

"""Train and test"""

from sklearn.naive_bayes import MultinomialNB
from sklearn.metrics import classification_report, confusion_matrix

nb = MultinomialNB()
nb.fit(X_train_num, y_train)
pred = nb.predict(X_test_num)
print(classification_report(y_test, pred, target_names=["ham","spam"]))

sns.heatmap(confusion_matrix(y_test, pred), annot=True, fmt="d", cmap="Blues",
            xticklabels=["ham","spam"], yticklabels=["ham","spam"])
plt.xlabel("Predicted"); plt.ylabel("Actual"); plt.title("Confusion matrix")
plt.show()

